// Social preview cards for every page. Layout.astro points each page's
// og:image at /open-graph/<route>.png, so every `route` passed to Layout needs
// a matching entry here.

import { readFileSync } from "node:fs";
import { join } from "node:path";
import type { APIRoute } from "astro";
import { getCollection } from "astro:content";
import satori from "satori";
import { html } from "satori-html";
import sharp from "sharp";
import {
  HOME,
  NOTES,
  NOTE_SERIES,
  NOTE_TAGS,
  PROJECTS,
  PROJECT_TAGS,
  SITE,
} from "@consts";
import { shouldRenderPage, slugify } from "@lib/utils";

const WIDTH = 1200;
const HEIGHT = 630;

type Card = { title: string; description?: string };

// Paths are relative to the repo root (builds run from there; import.meta.url
// would point into the bundled output instead).
const read = (path: string) => readFileSync(join(process.cwd(), path));
const dataUri = (path: string) => `data:image/png;base64,${read(path).toString("base64")}`;

// Generated by scripts/gen-og-assets.mjs.
const background = dataUri("images/og-background.png");
const logo = dataUri("images/og-logo.png");

const fonts = [
  { name: "Hanken Grotesk", data: read("src/fonts/HankenGrotesk-Regular.ttf"), weight: 400 },
  { name: "Hanken Grotesk", data: read("src/fonts/HankenGrotesk-ExtraBold.ttf"), weight: 800 },
  { name: "JetBrains Mono", data: read("src/fonts/JetBrainsMono-SemiBold.ttf"), weight: 600 },
] as const;

export async function getStaticPaths() {
  const cards: Record<string, Card> = {
    index: { title: SITE.TITLE, description: HOME.DESCRIPTION },
    about: { title: "About me", description: "All about me, Liam" },
    favorites: { title: "Favorites", description: "My favorite things" },
    projects: { title: PROJECTS.TITLE, description: PROJECTS.DESCRIPTION },
    "projects/tags": { title: PROJECT_TAGS.TITLE, description: PROJECT_TAGS.DESCRIPTION },
    notes: { title: NOTES.TITLE, description: NOTES.DESCRIPTION },
    "notes/tags": { title: NOTE_TAGS.TITLE, description: NOTE_TAGS.DESCRIPTION },
    "notes/series": { title: NOTE_SERIES.TITLE, description: NOTE_SERIES.DESCRIPTION },
    "404": { title: "404", description: "Page not found." },
  };

  const posts = (await getCollection("notes")).filter(shouldRenderPage);
  for (const post of posts) {
    cards[`${post.collection}/${post.id}`] = {
      title: post.data.title,
      description: post.data.description,
    };
  }

  const series = new Set(posts.map((post) => post.data.series).filter(Boolean) as string[]);
  for (const name of series) {
    cards[`notes/series/${slugify(name)}`] = { title: name, description: "A note series" };
  }

  return Object.entries(cards).map(([route, card]) => ({
    params: { route },
    props: card,
  }));
}

const escape = (value: string) =>
  value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export const GET: APIRoute = async ({ props }) => {
  const { title, description } = props as Card;

  const markup = html(`
    <div style="width: 100%; height: 100%; display: flex; position: relative; background: #0D0D0F;">
      <img src="${background}" style="position: absolute; top: 0; left: 0; width: ${WIDTH}px; height: ${HEIGHT}px;" />
      <div style="display: flex; flex-direction: column; justify-content: space-between; width: 100%; height: 100%; padding: 72px 80px;">
        <img src="${logo}" style="width: 88px; height: 88px;" />
        <div style="display: flex; flex-direction: column; gap: 20px; max-width: 860px;">
          <div style="font-family: 'Hanken Grotesk'; font-weight: 800; font-size: 76px; line-height: 1.05; letter-spacing: -0.02em; color: #F4F4F5;">
            ${escape(title)}
          </div>
          ${
            description
              ? `<div style="font-family: 'Hanken Grotesk'; font-size: 32px; line-height: 1.4; color: #A1A1AA;">${escape(description)}</div>`
              : ""
          }
          <div style="font-family: 'JetBrains Mono'; font-weight: 600; font-size: 26px; color: #F5A623; margin-top: 12px;">
            ${new URL(SITE.URL).host}
          </div>
        </div>
      </div>
    </div>
  `);

  const svg = await satori(markup, { width: WIDTH, height: HEIGHT, fonts: [...fonts] });
  const png = await sharp(Buffer.from(svg)).png().toBuffer();

  return new Response(new Uint8Array(png), {
    headers: { "Content-Type": "image/png" },
  });
};
